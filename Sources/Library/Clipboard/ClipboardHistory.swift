import CryptoKit
import ImageIO
import SwiftUI

/// A history of what was copied, kept in memory only. It is gone when the app quits.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory(historyFile: defaultHistoryFile)

    @Published private(set) var items: [ClipItem] = []
    /// What is on the clipboard now, if history recorded it. Nil after a copy that was skipped as private.
    @Published private(set) var current: ClipItem?
    /// Whether choosing an item pastes it when a text field has the keyboard. Otherwise it only copies.
    @Published var pastesIntoFields: Bool {
        didSet { UserDefaults.standard.set(pastesIntoFields, forKey: "clipboardPastesIntoFields") }
    }

    /// True when choosing an item should paste it now: the switch is on and a text field has the keyboard.
    var shouldPaste: Bool { pastesIntoFields && FrontApp.isTextInputFocused() }

    /// Whether copied web GIFs are downloaded so they can play. Off by default, since it contacts the copied page's server.
    @Published var playsGIFs: Bool {
        didSet { UserDefaults.standard.set(playsGIFs, forKey: "clipboardPlaysGIFs") }
    }
    @Published var isEnabled: Bool {
        didSet {
            UserDefaults.standard.set(isEnabled, forKey: "clipboardHistoryEnabled")
            isEnabled ? start() : stop()
        }
    }
    /// Whether unpinned history is saved to the history file, so it returns after a restart. Off by default. Turning it
    /// off deletes the file.
    @Published var keepsAcrossRestarts: Bool {
        didSet {
            UserDefaults.standard.set(keepsAcrossRestarts, forKey: "clipboardKeepsAcrossRestarts")
            guard keepsAcrossRestarts != oldValue else { return }
            if keepsAcrossRestarts {
                // A load that is already done or under way is merged by its own finish, so only a new load starts here.
                if historyLoadStarted { scheduleHistorySave() } else { loadHistory(atLaunch: false) }
            } else {
                historySave?.cancel()
                historySave = nil
                restoresLatestAtLaunch = false
                removeHistoryFile()
            }
        }
    }
    /// Whether the newest restored item is copied to the clipboard when Library opens. Only has an effect while
    /// `keepsAcrossRestarts` is on, and turning that off turns this off too.
    @Published var restoresLatestAtLaunch: Bool {
        didSet { UserDefaults.standard.set(restoresLatestAtLaunch, forKey: "clipboardRestoresLatest") }
    }

    private static let maxItems = 50
    nonisolated static let maxItemBytes = 25_000_000
    private static let maxTotalBytes = 200_000_000
    /// Text past this length is not indexed for search, which keeps each keystroke cheap.
    nonisolated private static let maxSearchableCharacters = 100_000
    /// Formats that password managers and system fields use to mark a copy as private. Those copies are skipped.
    nonisolated private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
    ]
    /// Password managers. Whatever is copied while one is in front is skipped, even without a private marker.
    nonisolated private static let ignoredApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.lastpass.lastpassmacdesktop",
        "com.dashlane.dashlanephonefinal", "com.apple.keychainaccess", "com.apple.Passwords",
    ]

    /// Pinned items are saved here, so text you keep survives a restart. Everything else stays in memory.
    nonisolated static let defaultFile = LibraryStore.dir.appendingPathComponent("clipboard.json")
    /// Unpinned history, saved only when `keepsAcrossRestarts` is on. Sealed with the same key as the pinned items.
    nonisolated static let defaultHistoryFile = LibraryStore.dir.appendingPathComponent("clipboard-history.json")

    private let pasteboard: NSPasteboard
    private let file: URL?
    /// Nil saves and restores nothing, so the checks and the default history never touch the real file.
    private let historyFile: URL?
    /// Supplies the key that encrypts pinned items and the history. Tests pass their own, so they never touch the Keychain.
    private let loadKey: @Sendable () throws -> SymmetricKey
    /// Deletes the Keychain key for Reset Clipboard Key. Tests pass their own, so they never touch the Keychain.
    private let resetKey: @Sendable () -> Void
    /// True when clipboard.json exists but could not be opened because the key was unavailable.
    private var leavesPinnedFile = false
    /// True when the history file exists but could not be opened because the key was unavailable. Nothing is written then.
    private var leavesHistoryFile = false
    /// False until the history file has been read. Until then nothing is written, so it cannot replace saved items.
    private(set) var historyLoaded = false
    /// Whether a history load has started, at launch or when the setting was turned on.
    private var historyLoadStarted = false
    /// Set when Clear History runs while the file is still loading. The restored clips are then dropped, not merged back.
    private var clearedWhileLoading = false
    /// The pending save of the history file. A copy made while one is pending joins it, since the save reads the
    /// history when it runs.
    private var historySave: Task<Void, Never>?
    /// When the history file was last written, so the next save waits out `historySaveInterval`.
    private var lastHistoryWrite: Date?
    /// The change count when Library opened. A copy made since then means the clipboard is not replaced at launch.
    private let launchChangeCount: Int
    /// False until clipboard.json has been read in the background. Until then nothing is written, so a save can
    /// never replace the pinned items that are still loading.
    private(set) var pinnedLoaded = false
    /// A pin or unpin that happened before the load finished. It is written once the load is merged.
    private var savesAfterLoad = false
    /// Every write of clipboard.json runs here, one at a time and in the order they were queued.
    private static let writeQueue = DispatchQueue(label: "com.deansasek.library.clipboard-save")
    /// True once a save has failed and the user has been told. Cleared by the next save that works, so a folder that
    /// stays unwritable is reported once rather than on every copy.
    private static var reportedWriteFailure = false
    private var timer: Timer?
    private var lastChange: Int
    /// An app that has been in front since the last poll, so a copy seen late is judged by the app that made it.
    private struct FrontmostApp {
        var bundleID: String
        var name: String?
    }
    /// Every app that was in front since the last poll, oldest first, ending with the app in front now.
    private var appsFrontSinceLastPoll: [FrontmostApp] = []
    /// Watches for app switches, since a copy can be noticed up to 0.75 s after it was made.
    private var activationObserver: NSObjectProtocol?
    /// Counts copies, so an older copy that finishes building late does not take over `current`.
    private var captureGeneration = 0
    /// Counts Clear History presses, so a copy that started building before the last one is not added after it. A
    /// build carries the value it saw at `poll` and is dropped when the counter has moved on.
    private var clearEpoch = 0
    /// The clear count, so a check can add a built copy with the epoch the current history is on.
    var clearEpochForChecks: Int { clearEpoch }
    /// Copies still being built in the background. Zero once every copy has been added.
    private(set) var pendingCaptures = 0

    /// `pasteboard` is the system clipboard, or another one for checking the history without touching it.
    /// `file` is where pinned items are saved. Nil saves nothing. `key` encrypts that file.
    /// `historyFile` is where unpinned history is saved when it is kept across restarts. Nil saves nothing.
    init(pasteboard: NSPasteboard = .general, file: URL? = ClipboardHistory.defaultFile, historyFile: URL? = nil,
         key: @escaping @Sendable () throws -> SymmetricKey = ClipboardKey.key,
         resetKey: @escaping @Sendable () -> Void = ClipboardKey.reset) {
        self.pasteboard = pasteboard
        self.file = file
        self.historyFile = historyFile
        self.loadKey = key
        self.resetKey = resetKey
        lastChange = pasteboard.changeCount
        launchChangeCount = pasteboard.changeCount
        isEnabled = UserDefaults.standard.object(forKey: "clipboardHistoryEnabled") as? Bool ?? true
        playsGIFs = UserDefaults.standard.object(forKey: "clipboardPlaysGIFs") as? Bool ?? false
        pastesIntoFields = UserDefaults.standard.object(forKey: "clipboardPastesIntoFields") as? Bool ?? true
        keepsAcrossRestarts = UserDefaults.standard.object(forKey: "clipboardKeepsAcrossRestarts") as? Bool ?? false
        restoresLatestAtLaunch = UserDefaults.standard.object(forKey: "clipboardRestoresLatest") as? Bool ?? false
        loadPinned()
        if historyFile != nil {
            // Off means no file: a file left from an earlier setting is removed, not read.
            if keepsAcrossRestarts { loadHistory(atLaunch: true) } else { removeHistoryFile() }
        }
        if isEnabled { start() }
    }

    /// The pinned items read from clipboard.json, built off the main actor and then published on it.
    private struct PinnedLoad: Sendable {
        var items: [ClipItem]
        /// The file was plain JSON from before encryption, so it must be saved again.
        var migrated: Bool
        /// The file exists but could not be opened with the key, so nothing may be written over it.
        var leavesFile: Bool
    }

    /// The unpinned items read from the history file. Built off the main actor, like the pins.
    private struct HistoryLoad: Sendable {
        var items: [ClipItem]
        /// The file exists but could not be opened with the key, so nothing may be written over it.
        var leavesFile: Bool
    }

    /// Reads clipboard.json in the background: the file, the Keychain key, decryption, decoding, and building every
    /// item with its thumbnail. The main actor is not used until the result is published.
    private func loadPinned() {
        guard let file else {
            pinnedLoaded = true
            return
        }
        let loadKey = self.loadKey
        Task.detached(priority: .userInitiated) { [weak self] in
            let load = ClipboardHistory.readPinned(file: file, key: loadKey)
            await self?.finishLoading(load)
        }
    }

    /// Nil when there is no file. Runs off the main actor.
    nonisolated private static func readPinned(file: URL, key loadKey: @Sendable () throws -> SymmetricKey) -> PinnedLoad? {
        guard FileManager.default.fileExists(atPath: file.path) else { return nil }
        guard let data = try? Data(contentsOf: file) else {
            NSLog("Library: could not read clipboard.json, so pinned items were not loaded")
            return PinnedLoad(items: [], migrated: false, leavesFile: true)
        }
        let key: SymmetricKey?
        do {
            key = try loadKey()
        } catch {
            NSLog("Library: pinned clipboard key unavailable, so pinned items were not loaded: \(error)")
            key = nil
        }
        switch PinnedFile.read(data, key: key) {
        case .clips(let clips, let migrated):
            // Without a key, the file was not verified, so nothing may overwrite or delete it until a later launch.
            return PinnedLoad(items: items(from: clips, pinned: true), migrated: migrated, leavesFile: key == nil)
        case .unreadable:
            // With no key, the file may be fine, so it is left alone. With a key, it is damaged: keep it for
            // inspection and start with no pins.
            guard key != nil else { return PinnedLoad(items: [], migrated: false, leavesFile: true) }
            // If the file cannot be moved aside, it stays where it is and nothing may overwrite it.
            let moved = quarantine(file, stem: "clipboard-damaged", ext: "bin")
            return PinnedLoad(items: [], migrated: false, leavesFile: !moved)
        }
    }

    /// The items for saved clips, with their thumbnails. Off the main actor.
    nonisolated private static func items(from clips: [PinnedFile.Clip], pinned: Bool) -> [ClipItem] {
        clips.compactMap { clip in
            let representations = clip.representations.map { representation in
                Dictionary(uniqueKeysWithValues: representation.map { (NSPasteboard.PasteboardType($0.key), $0.value) })
            }
            let bytes = representations.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } }
            guard var item = makeItem(representations: representations, bytes: bytes, date: clip.date) else { return nil }
            item.pinned = pinned
            item.sourceApp = clip.source
            return item
        }
    }

    /// Reads the history file in the background. Nil when there is no file. Off the main actor.
    nonisolated private static func readHistory(file: URL, key loadKey: @Sendable () throws -> SymmetricKey) -> HistoryLoad? {
        guard FileManager.default.fileExists(atPath: file.path) else { return nil }
        guard let data = try? Data(contentsOf: file) else {
            NSLog("Library: could not read clipboard-history.json, so history was not restored")
            return HistoryLoad(items: [], leavesFile: true)
        }
        let key: SymmetricKey?
        do {
            key = try loadKey()
        } catch {
            NSLog("Library: clipboard history key unavailable, so history was not restored: \(error)")
            key = nil
        }
        // With no key, nothing is restored and the file is left alone until a later launch.
        guard key != nil else { return HistoryLoad(items: [], leavesFile: true) }
        switch HistoryFile.read(data, key: key) {
        case .clips(let clips):
            return HistoryLoad(items: items(from: clips, pinned: false), leavesFile: false)
        case .unreadable:
            let moved = quarantine(file, stem: "clipboard-history-damaged", ext: "bin")
            return HistoryLoad(items: [], leavesFile: !moved)
        }
    }

    /// Reads the history file in the background, then merges it on the main actor. `atLaunch` allows the latest item to
    /// go on the clipboard. A load started by turning the setting on never does.
    private func loadHistory(atLaunch: Bool) {
        historyLoadStarted = true
        guard let historyFile else {
            historyLoaded = true
            return
        }
        let loadKey = self.loadKey
        Task.detached(priority: .userInitiated) { [weak self] in
            let load = ClipboardHistory.readHistory(file: historyFile, key: loadKey)
            await self?.finishHistoryLoading(load, atLaunch: atLaunch)
        }
    }

    /// Merges the restored items after the copies and pins already here, applies the limits, and copies the newest
    /// restored item when that setting is on and nothing was copied since launch.
    private func finishHistoryLoading(_ load: HistoryLoad?, atLaunch: Bool) {
        historyLoaded = true
        let clearedDuringLoad = clearedWhileLoading
        clearedWhileLoading = false
        // Turned off while loading: the file was already removed, and nothing is restored.
        guard keepsAcrossRestarts else { return }
        if let load {
            leavesHistoryFile = load.leavesFile
            // Clear History ran before the file was read, so the clips in it were cleared too.
            let restored = clearedDuringLoad ? [] : load.items
            items = HistoryRestart.merge(items, restored: restored)
            trim()
            let latest = atLaunch ? HistoryRestart.latest(in: restored) : nil
            if let latest, HistoryRestart.copiesLatestAtLaunch(keeps: keepsAcrossRestarts,
                                                               restoresLatest: restoresLatestAtLaunch,
                                                               latest: latest,
                                                               copiedSinceLaunch: pasteboard.changeCount != launchChangeCount) {
                copy(latest)
                // The copy is already in the history, so the watcher must not record it again.
                lastChange = pasteboard.changeCount
                current = latest
            }
        }
        scheduleHistorySave()
    }

    /// The history is saved at most once per `historySaveInterval` while copies keep coming, and at least a second
    /// after the first copy of a burst. Copies made while a save is pending share it. Quitting always saves (flushHistory).
    nonisolated static let historySaveInterval: TimeInterval = 10
    nonisolated static let historySaveDebounce: TimeInterval = 1

    /// How long until the next history save may run: at least `historySaveDebounce`, and no sooner than
    /// `historySaveInterval` after the last write. Pure, so the checks can test the timing.
    nonisolated static func historySaveDelay(lastWrite: Date?, now: Date) -> TimeInterval {
        guard let lastWrite else { return historySaveDebounce }
        return max(historySaveDebounce, lastWrite.addingTimeInterval(historySaveInterval).timeIntervalSince(now))
    }

    /// Schedules the history save. Only one is pending at a time: it reads the history when it runs, so it includes
    /// every copy made until then.
    private func scheduleHistorySave() {
        guard keepsAcrossRestarts, historyFile != nil, historySave == nil else { return }
        let delay = Self.historySaveDelay(lastWrite: lastHistoryWrite, now: Date())
        historySave = Task { [weak self] in
            try? await Task.sleep(for: .seconds(delay))
            guard !Task.isCancelled else { return }
            self?.writeHistory()
        }
    }

    /// The unpinned items to save now, or nil when nothing may be written: the setting is off, the file has not been read
    /// yet, or it could not be opened with the key. Built on the main actor, where the items live.
    private func historyClips() -> [PinnedFile.Clip]? {
        guard keepsAcrossRestarts, historyLoaded, !leavesHistoryFile else { return nil }
        return items.filter {
            HistoryRestart.saves(kind: $0.kind, byteCount: $0.byteCount, pinned: $0.pinned, keeps: true)
        }.map { item in
            PinnedFile.Clip(source: item.sourceApp, date: item.date, representations: item.representations.map { representation in
                Dictionary(uniqueKeysWithValues: representation.map { ($0.key.rawValue, $0.value) })
            })
        }
    }

    private func writeHistory() {
        historySave = nil
        guard let historyFile, let clips = historyClips() else { return }
        lastHistoryWrite = Date()
        let loadKey = self.loadKey
        Self.writeQueue.async { Self.persistHistory(clips, to: historyFile, key: loadKey) }
    }

    /// Writes the unpinned history before Library quits. It waits for the write, since the app may exit right after.
    func flushHistory() {
        historySave?.cancel()
        historySave = nil
        // Whatever is already queued has to finish before this returns, since the app may exit right after. A pin
        // made moments before the quit is queued on writeQueue, and with history off there is nothing else here that
        // would wait for it, so it is drained here rather than after the guard below.
        Self.writeQueue.sync {}
        guard let historyFile, let clips = historyClips() else { return }
        lastHistoryWrite = Date()
        let loadKey = self.loadKey
        Self.writeQueue.sync { Self.persistHistory(clips, to: historyFile, key: loadKey) }
    }

    /// Whether the user is told about a failed write. Only the first failure of a streak speaks, so a folder that
    /// stays unwritable does not repeat the message on every copy. A write that works clears the streak.
    nonisolated static func reportsWriteFailure(reported: Bool) -> Bool { !reported }

    /// Writes `data` to `file` through a temporary file that is private from the moment it is created, so the text is
    /// never readable by anyone else, not even briefly. False when the temporary file could not be created or could
    /// not be moved into place, which is logged rather than passed over in silence. Runs on `writeQueue`.
    nonisolated static func writeAtomically(_ data: Data, to file: URL, stem: String) -> Bool {
        let folder = file.deletingLastPathComponent()
        let temporary = folder.appendingPathComponent(".\(stem)-\(UUID().uuidString).tmp")
        guard FileManager.default.createFile(atPath: temporary.path, contents: data, attributes: [.posixPermissions: 0o600]) else {
            NSLog("Library: \(file.lastPathComponent) was not saved, because no temporary file could be created in \(folder.path)")
            return false
        }
        guard rename(temporary.path, file.path) == 0 else {
            NSLog("Library: \(file.lastPathComponent) was not saved, because its temporary file could not be moved into place")
            try? FileManager.default.removeItem(at: temporary)
            return false
        }
        return true
    }

    /// Seals the items and writes them atomically, or removes the file when none are left. Runs on `writeQueue`.
    /// Nothing is written when the key is unavailable, so no plain text is ever saved.
    nonisolated private static func persistHistory(_ clips: [PinnedFile.Clip], to file: URL, key loadKey: @Sendable () throws -> SymmetricKey) {
        guard !clips.isEmpty else {
            try? FileManager.default.removeItem(at: file)
            return
        }
        let data: Data
        do {
            data = try HistoryFile.encode(clips, key: loadKey())
        } catch {
            NSLog("Library: clipboard history was not saved, because the key is unavailable: \(error)")
            return
        }
        // Same as clipboard.json: the temporary file is private from creation, then renamed over the old file.
        noteWrite(writeAtomically(data, to: file, stem: "clipboard-history"))
    }

    /// Deletes the history file, after any write already queued. Used when the setting is turned off.
    private func removeHistoryFile() {
        guard let historyFile else { return }
        Self.writeQueue.async { try? FileManager.default.removeItem(at: historyFile) }
    }

    /// Publishes the loaded pins. Copies made while the file was loading stay first. A pin whose copy was made
    /// again during the load is marked pinned instead of added twice. The rest go in by copy time, as a copy does.
    private func finishLoading(_ load: PinnedLoad?) {
        pinnedLoaded = true
        if let load {
            leavesPinnedFile = load.leavesFile
            for pin in load.items {
                if let index = items.firstIndex(where: { $0.digest == pin.digest }) {
                    items[index].pinned = true
                } else {
                    items.insert(pin, at: items.firstIndex { $0.date < pin.date } ?? items.count)
                }
            }
            trim()
        }
        if load?.migrated == true || savesAfterLoad {
            savesAfterLoad = false
            savePinned()
        }
    }

    /// Moves a damaged file aside under a new timestamped name, so an earlier copy is never replaced. The file is kept
    /// for inspection. Returns false when it could not be moved, and then the file is left where it is.
    nonisolated private static func quarantine(_ file: URL, stem: String, ext: String) -> Bool {
        guard let moved = DamagedCopy.preserve(file, stem: stem, ext: ext, moving: true) else { return false }
        NSLog("Library: \(file.lastPathComponent) could not be read, so it was moved to \(moved.lastPathComponent)")
        return true
    }

    /// Waits until every write queued so far has finished. Used by the checks, which read the file right after a save.
    static func waitForSaves() {
        writeQueue.sync {}
    }

    /// Writes the pinned items to clipboard.json, sealed with the Keychain key, or removes the file when none are
    /// left. If the key is unavailable, nothing is written, so no plain text is ever saved. The items are sealed
    /// here, and the bytes are written on `writeQueue`, so the file is never touched on the main actor.
    private func savePinned() {
        guard pinnedLoaded else {
            savesAfterLoad = true
            return
        }
        guard let file else { return }
        guard !leavesPinnedFile else {
            NSLog("Library: pinned clipboard items were not saved, because clipboard.json was not opened this launch")
            return
        }
        // Only the copy of the clips is made here. Sealing them can wait for the Keychain, so it runs on the write
        // queue, in the order the saves were requested.
        let clips = items.filter(\.pinned).map { item in
            PinnedFile.Clip(source: item.sourceApp, date: item.date, representations: item.representations.map { representation in
                Dictionary(uniqueKeysWithValues: representation.map { ($0.key.rawValue, $0.value) })
            })
        }
        guard !clips.isEmpty else {
            Self.writeQueue.async { try? FileManager.default.removeItem(at: file) }
            return
        }
        let loadKey = self.loadKey
        // The temporary file is private from the moment it is created, then renamed over the old one, so the
        // text is never readable by anyone else, not even briefly.
        Self.writeQueue.async {
            let data: Data
            do {
                data = try PinnedFile.encode(clips, key: loadKey())
            } catch {
                NSLog("Library: pinned clipboard items were not saved, because the key is unavailable: \(error)")
                return
            }
            Self.noteWrite(Self.writeAtomically(data, to: file, stem: "clipboard"))
        }
    }

    /// Tells the user once that a save did not reach disk. Runs off the main actor, from `writeQueue`, so a copy is
    /// never held up by the message. The items stay in memory, so the next save writes them once the folder works.
    nonisolated private static func noteWrite(_ wrote: Bool) {
        Task { @MainActor in
            if wrote {
                reportedWriteFailure = false
            } else if reportsWriteFailure(reported: reportedWriteFailure) {
                reportedWriteFailure = true
                NSSound.beep()
                AccessibilityNotification.Announcement(
                    String(localized: "Library could not save your clipboard items. Check that its folder can be written to, then try again.",
                           bundle: L10n.bundle)).post()
            }
        }
    }

    /// Reset Clipboard Key. Deletes the Keychain key and the saved pinned items, and the saved history, which the old key
    /// sealed. Pinned items are removed from memory and the paste queue. Unpinned items stay, and are saved again under
    /// the new key when history is kept across restarts. Does nothing until the pinned items have loaded.
    func resetClipboardKey() {
        guard pinnedLoaded else { return }
        let pinned = items.filter(\.pinned)
        items.removeAll { $0.pinned }
        forget(pinned)
        historySave?.cancel()
        historySave = nil
        let pinnedFile = file
        let historyFileURL = historyFile
        let resetKey = self.resetKey
        // Queued on writeQueue, so any save already waiting finishes first and none runs with the new key.
        Self.writeQueue.sync {
            if let pinnedFile { try? FileManager.default.removeItem(at: pinnedFile) }
            if let historyFileURL { try? FileManager.default.removeItem(at: historyFileURL) }
            resetKey()
        }
        leavesPinnedFile = false
        leavesHistoryFile = false
        Self.reportedWriteFailure = false
        scheduleHistorySave()
    }

    /// Pinned items first, then the rest, newest first in each group.
    var displayOrder: [ClipItem] {
        items.filter(\.pinned) + items.filter { !$0.pinned }
    }

    /// The apps that copied something in the history, each once, in name order. A locked pinned item is left out, so
    /// its source app is not listed before the user authenticates.
    var sourceApps: [String] {
        Self.sourceApps(in: items) { ClipboardLock.shared.isHidden($0) }
    }

    /// The source apps of the items that are not hidden, each once, in name order.
    nonisolated static func sourceApps(in items: [ClipItem], isHidden: (ClipItem) -> Bool) -> [String] {
        Array(Set(items.filter { !isHidden($0) }.compactMap(\.sourceApp))).sorted()
    }

    /// Items whose text contains every word. With `app`, only the items copied while that app was in front.
    func search(_ query: String, from app: String? = nil) -> [ClipItem] {
        let words = query.lowercased().split(separator: " ").map(String.init)
        // Built once for this search. Each item's text was capped at maxSearchableCharacters when it was copied.
        // A locked pinned item is left out, so a search cannot reveal its text before the user authenticates.
        // With `app`, only the items copied while that app was in front.
        let order = displayOrder.filter { item in
            !ClipboardLock.shared.isHidden(item) && (app.map { SourceFilter.includes(item.sourceApp, app: $0) } ?? true)
        }
        guard !words.isEmpty else { return order }
        return order.filter { item in words.allSatisfy(item.searchText.contains) }
    }

    // MARK: Actions

    /// Puts the item back on the clipboard in every format it had. A link has its tracking parameters removed
    /// when the setting is on; the history keeps the link as it was copied.
    func copy(_ item: ClipItem) {
        // A file that was moved or deleted is not copied, so no dead file reference reaches the pasteboard.
        guard !Self.refersToMissingFile(item) else {
            NSSound.beep()
            return
        }
        let cleans = item.kind == .link && TrackingPreferences.shared.removesOnCopy
        pasteboard.clearContents()
        pasteboard.writeObjects(item.representations.map { representation in
            let pasteboardItem = NSPasteboardItem()
            representation.forEach { type, data in
                pasteboardItem.setData(cleans ? Self.cleaned(data, type: type) : data, forType: type)
            }
            return pasteboardItem
        })
    }

    /// True when the item names a file that is no longer on disk.
    static func refersToMissingFile(_ item: ClipItem, exists: (URL) -> Bool = { FileManager.default.fileExists(atPath: $0.path) }) -> Bool {
        item.fileURLs.contains { !exists($0) }
    }

    /// The link text, with tracking parameters removed, for the formats that carry the link. Other data is unchanged.
    private static func cleaned(_ data: Data, type: NSPasteboard.PasteboardType) -> Data {
        guard type == .string || type == .URL else { return data }
        let link = String(decoding: data, as: UTF8.self)
        let clean = TrackingParameters.clean(link)
        return clean == link ? data : Data(clean.utf8)
    }

    func copyPlainText(_ item: ClipItem) {
        guard let text = item.plainText else { return }
        copyText(text)
    }

    /// Puts `text` on the clipboard as plain text. It becomes a new entry when the change is seen, and the history keeps
    /// what it had.
    func copyText(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    /// Pins or unpins an item. Pinning is refused, and says so, when the pinned items would pass the total size limit.
    @discardableResult
    func togglePin(_ item: ClipItem) -> Bool {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return false }
        if !items[index].pinned {
            let pinnedBytes = items.reduce(0) { $0 + ($1.pinned ? $1.byteCount : 0) }
            guard HistoryRestart.canPin(byteCount: items[index].byteCount, pinnedBytes: pinnedBytes) else {
                NSSound.beep()
                AccessibilityNotification.Announcement(String(localized: "Pinned clips can’t total more than 200 MB. Unpin a clip to make room.", bundle: L10n.bundle)).post()
                return false
            }
        }
        items[index].pinned.toggle()
        savePinned()
        scheduleHistorySave()
        return true
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        forget([item])
        if item.pinned { savePinned() }
        scheduleHistorySave()
    }

    /// Removes the clips that refer to a file, such as a screen recording that was deleted.
    func removeFile(at url: URL) {
        let pinnedRemoved = items.contains { $0.pinned && $0.fileURLs.contains(url) }
        let before = items.count
        items.removeAll { $0.fileURLs.contains(url) }
        guard items.count != before else { return }
        if pinnedRemoved { savePinned() }
        scheduleHistorySave()
    }

    /// Downloads the GIF a copied web image points at and attaches it, so the picture can play. Browsers copy a
    /// still picture, with the real address only in the HTML. This asks the site for that one file.
    private func fetchGIF(digest: String, from url: URL) {
        Task {
            // Only web addresses, and the download stops at the item size limit.
            guard let (data, response) = await WebFetch.fetch(url, limit: Self.maxItemBytes),
                  response.statusCode == 200,
                  data.starts(with: Array("GIF8".utf8)),
                  let index = items.firstIndex(where: { $0.digest == digest }) else { return }
            items[index].animatedData = data
            items[index].byteCount += data.count
            if current?.digest == digest { current = items[index] }
            trim()
        }
    }

    /// Removes everything that is not pinned.
    func clear() {
        if historyLoadStarted && !historyLoaded { clearedWhileLoading = true }
        // A copy still being built belongs to the history the user just cleared, so it is counted as belonging to an
        // earlier clear and dropped when its build finishes.
        clearEpoch &+= 1
        let removed = items.filter { !$0.pinned }
        items.removeAll { !$0.pinned }
        forget(removed)
        scheduleHistorySave()
    }

    /// Drops removed clips from what still reaches them: the current clip, which the menus suggest adding to the
    /// library, and the paste queue.
    private func forget(_ removed: [ClipItem]) {
        let ids = Set(removed.map(\.id))
        if let current, ids.contains(current.id) { self.current = nil }
        pasteQueue.removeAll { ids.contains($0.id) }
    }

    // MARK: Paste queue

    /// Clips to paste one at a time, in order. Kept in memory only, so it is empty again when Library starts.
    @Published private(set) var pasteQueue: [ClipItem] = []

    func enqueue(_ item: ClipItem) {
        pasteQueue.append(item)
    }

    /// Adds a screenshot or recording that macOS saved to disk. The pasteboard and the current item are left alone.
    func addCapture(_ representations: [[NSPasteboard.PasteboardType: Data]], source: String) {
        guard isEnabled else { return }
        let bytes = representations.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } }
        guard let item = Self.makeItem(representations: representations, bytes: bytes) else { return }
        add(item, source: source, fromLibrary: false, generation: -1, epoch: clearEpoch)
    }

    /// Copies the first queued clip and takes it out of the queue. A Command-V in the app in front then pastes it.
    func pasteNext() {
        guard let next = pasteQueue.first else { return }
        // A locked pinned item is copied only after the user authenticates, as it is everywhere else. It stays queued
        // until then. The queue is checked again, so a second request does not take a different clip.
        ClipboardLock.shared.perform(next, for: .copy) { [weak self] in
            guard let self, self.pasteQueue.first?.id == next.id else { return }
            self.pasteQueue.removeFirst()
            self.copy(next)
        }
    }

    func clearPasteQueue() {
        pasteQueue.removeAll()
    }

    // MARK: Watching

    /// macOS sends no event when the clipboard changes, so the change counter is checked twice a second. The
    /// timer is loose so the system can batch its wake-ups, and it is off while history is off.
    private func start() {
        guard timer == nil else { return }
        lastChange = pasteboard.changeCount
        // The app in front when watching starts is the first one a copy may have been made in.
        appsFrontSinceLastPoll = NSWorkspace.shared.frontmostApplication.map { [Self.frontApp($0)] } ?? []
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] note in
            let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            MainActor.assumeIsolated { self?.didActivate(app) }
        }
        let timer = Timer(timeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { [weak self] in self?.poll() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
        if let activationObserver {
            NSWorkspace.shared.notificationCenter.removeObserver(activationObserver)
            self.activationObserver = nil
        }
        appsFrontSinceLastPoll.removeAll()
    }

    /// Records an app coming to the front. The app it replaced stays in the window, so a copy made just before the
    /// switch is still judged by the app that made it.
    private func didActivate(_ app: NSRunningApplication?) {
        guard let app, app.bundleIdentifier != appsFrontSinceLastPoll.last?.bundleID else { return }
        appsFrontSinceLastPoll.append(Self.frontApp(app))
    }

    private static func frontApp(_ app: NSRunningApplication) -> FrontmostApp {
        FrontmostApp(bundleID: app.bundleIdentifier ?? "", name: app.localizedName)
    }

    /// Whether a copy is skipped: a private type marks it, or any app that was in front since the last poll is a
    /// password manager. `frontmost` holds every bundle identifier in that window, so a copy made just before the
    /// user switched away is still judged by the app that made it.
    nonisolated static func isIgnoredCopy(frontmost: Set<String>, types: Set<String>) -> Bool {
        !frontmost.isDisjoint(with: ignoredApps) || !types.isDisjoint(with: privateTypes)
    }

    /// The app that made a copy seen at poll time. `frontmost` lists the apps that were in front since the last
    /// poll, oldest first. A copy made just before a switch came from the app before the one in front now; without
    /// a switch it is the app in front now. Nil when no app was recorded.
    nonisolated static func copySourceApp(frontmost: [String]) -> String? {
        guard !frontmost.isEmpty else { return nil }
        return frontmost.count > 1 ? frontmost[frontmost.count - 2] : frontmost[0]
    }

    /// Reads the copy on the main thread, then builds the item in the background, so a large copy does not stall
    /// the menus.
    func poll() {
        // The apps in front since the last poll, with the app in front now last. The window only spans one poll,
        // since any copy older than that was seen by an earlier poll. It is reset to the app in front now, which
        // is the first app a later copy may be made in.
        let frontApps = appsFrontSinceLastPoll
        if let front = frontApps.last { appsFrontSinceLastPoll = [front] }
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        current = nil
        captureGeneration += 1
        let generation = captureGeneration
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty,
              !Self.isIgnoredCopy(frontmost: Set(frontApps.map(\.bundleID)),
                                 types: Set(pasteboardItems.flatMap { $0.types.map(\.rawValue) })),
              let copied = Self.collect(pasteboardItems) else { return }
        let sourceID = Self.copySourceApp(frontmost: frontApps.map(\.bundleID))
        let fromLibrary = sourceID == Bundle.main.bundleIdentifier
        let source = fromLibrary ? nil : frontApps.first { $0.bundleID == sourceID }?.name
        pendingCaptures += 1
        let epoch = clearEpoch
        Task {
            defer { pendingCaptures -= 1 }
            let built = await Task.detached(priority: .userInitiated) {
                Self.makeItem(representations: copied.representations, bytes: copied.bytes)
            }.value
            guard let built else { return }
            add(built, source: source, fromLibrary: fromLibrary, generation: generation, epoch: epoch)
        }
    }

    /// Adds a copy that has finished building. `epoch` is the clear count `poll` saw: a build that started before a
    /// Clear History is dropped, since the user asked for it to be gone, and so is one made while history was off. Internal
    /// so the checks can add a built copy on their own.
    func add(_ copy: ClipItem, source: String?, fromLibrary: Bool, generation: Int, epoch: Int) {
        guard epoch == clearEpoch, isEnabled else { return }
        var item = copy
        // Copying something again, or copying an item back from the history, moves it to the top.
        var previous: ClipItem?
        if let index = items.firstIndex(where: { $0.digest == item.digest }) {
            previous = items.remove(at: index)
            item.pinned = previous?.pinned ?? false
        }
        // When Library itself is in front, the copy came from choosing an item in its own menu. Keep the source
        // the item already had instead of replacing it with nothing.
        item.sourceApp = fromLibrary ? previous?.sourceApp : source
        // Builds can finish out of order, so each item goes where its copy time puts it. The newest stays first.
        items.insert(item, at: items.firstIndex { $0.date < item.date } ?? items.count)
        if generation == captureGeneration { current = item }
        trim()
        scheduleHistorySave()
        if playsGIFs, let url = item.gifURL, !item.isAnimated { fetchGIF(digest: item.digest, from: url) }
    }

    /// Reads every format of what was copied, keeping one image format. Nil when it is over the size limit.
    private static func collect(_ pasteboardItems: [NSPasteboardItem])
        -> (representations: [[NSPasteboard.PasteboardType: Data]], bytes: Int)? {
        var representations: [[NSPasteboard.PasteboardType: Data]] = []
        var bytes = 0
        for pasteboardItem in pasteboardItems {
            var representation: [NSPasteboard.PasteboardType: Data] = [:]
            // A copied image arrives as both PNG and TIFF. Keeping both would double its memory.
            let hasPNG = pasteboardItem.types.contains(.png)
            for type in pasteboardItem.types {
                if type == .tiff && hasPNG { continue }
                guard let data = pasteboardItem.data(forType: type) else { continue }
                bytes += data.count
                if bytes > maxItemBytes { return nil }
                representation[type] = data
            }
            if !representation.isEmpty { representations.append(representation) }
        }
        return (representations, bytes)
    }

    /// Works out what an item is and how to show it.
    nonisolated private static func makeItem(representations: [[NSPasteboard.PasteboardType: Data]], bytes: Int,
                                 date: Date = Date()) -> ClipItem? {
        guard let first = representations.first else { return nil }
        var hasher = SHA256()
        for representation in representations {
            for (type, data) in representation.sorted(by: { $0.key.rawValue < $1.key.rawValue }) {
                hasher.update(data: Data(type.rawValue.utf8))
                hasher.update(data: data)
            }
        }
        let digest = hasher.finalize().map { String(format: "%02x", $0) }.joined()

        let text = first[.string].flatMap { String(data: $0, encoding: .utf8) }
        let files = representations.compactMap { $0[.fileURL] }
            .compactMap { String(data: $0, encoding: .utf8) }.compactMap { URL(string: $0) }
        let kind: ClipItem.Kind
        var title: String
        var link: URL?
        var thumbnail: NSImage?
        let gifURL = first[.html].flatMap { String(data: $0, encoding: .utf8) }.flatMap(Self.gifURL(in:))
        if !files.isEmpty {
            kind = .file
            title = files.map(\.lastPathComponent).joined(separator: ", ")
        } else if first[.png] != nil || first[.tiff] != nil || first[ClipItem.gifType] != nil {
            kind = .image
            let picture = (first[.png] ?? first[.tiff] ?? first[ClipItem.gifType]).flatMap { NSImage(data: $0) }
            title = picture.map { "Image \(Int($0.size.width)) × \(Int($0.size.height))" } ?? "Image"
            thumbnail = (first[.png] ?? first[.tiff] ?? first[ClipItem.gifType]).flatMap(Self.thumbnail(of:))
        } else if let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            link = QuickOpenResult.link(from: text)
            kind = link == nil ? .text : .link
            // The first non-empty line, with runs of white space shortened.
            let line = text.split(whereSeparator: \.isNewline).first { !$0.allSatisfy(\.isWhitespace) } ?? ""
            title = String(line.split(whereSeparator: \.isWhitespace).joined(separator: " ").prefix(100))
        } else {
            kind = .other
            title = "Clipboard Item"
        }
        var item = ClipItem(representations: representations, digest: digest, kind: kind, title: title,
                            plainText: text, link: link, thumbnail: thumbnail, gifURL: gifURL, fileURLs: files,
                            byteCount: bytes)
        item.date = date
        item.searchText = String("\(text ?? "") \(title)".lowercased().prefix(maxSearchableCharacters))
        return item
    }

    /// The first image in copied HTML whose address ends in .gif.
    nonisolated private static func gifURL(in html: String) -> URL? {
        guard let regex = try? NSRegularExpression(pattern: #"<img[^>]*\ssrc\s*=\s*["']([^"']+)["']"#, options: .caseInsensitive)
        else { return nil }
        for match in regex.matches(in: html, range: NSRange(html.startIndex..., in: html)) {
            guard let range = Range(match.range(at: 1), in: html), let url = URL(string: String(html[range])),
                  WebFetch.isWeb(url), url.path.lowercased().hasSuffix(".gif") else { continue }
            return url
        }
        return nil
    }

    /// The most pixels a clipboard picture may have before it gets a thumbnail. ImageIO decodes the picture to make a
    /// thumbnail, so the size is checked from the header first. A 5K screenshot is well under this.
    nonisolated static let maxThumbnailPixels = 40_000_000

    /// Whether a picture of this size may be decoded for a thumbnail.
    nonisolated static func thumbnailSizeAllowed(width: Int, height: Int) -> Bool {
        width > 0 && height > 0 && width * height <= maxThumbnailPixels
    }

    /// A picture of at most 16 pt, decoded straight to that size so the full image is never kept. Nil when the header
    /// does not give a size, or the picture is larger than `maxThumbnailPixels`.
    nonisolated private static func thumbnail(of data: Data) -> NSImage? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              thumbnailSizeAllowed(width: width, height: height),
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                  kCGImageSourceCreateThumbnailFromImageAlways: true,
                  kCGImageSourceThumbnailMaxPixelSize: 16,
              ] as CFDictionary) else { return nil }
        return NSImage(cgImage: image, size: NSSize(width: image.width, height: image.height))
    }

    /// Keeps the newest unpinned items within the count and memory limits.
    private func trim() {
        let kept = HistoryRestart.limited(items, maxItems: Self.maxItems, maxTotalBytes: Self.maxTotalBytes)
        if kept.count != items.count { items = kept }
    }
}
